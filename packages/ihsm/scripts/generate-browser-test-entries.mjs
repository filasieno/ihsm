#!/usr/bin/env node
/** Generate test/browser/entries/*.ts from spec globs. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const entriesDir = path.join(repoRoot, 'test/browser/entries');

function walkSpecs(dir, suffix) {
	const out = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			out.push(...walkSpecs(full, suffix));
		} else if (entry.name.endsWith(suffix) && !entry.name.endsWith('.node.spec.ts')) {
			out.push(full);
		}
	}
	return out.sort();
}

function relImport(fromEntry, absSpec) {
	return path.relative(path.dirname(fromEntry), absSpec).split(path.sep).join('/');
}

function writeEntry(name, specPaths) {
	const entryFile = path.join(entriesDir, `${name}.ts`);
	const imports = specPaths.map(spec => `import '${relImport(entryFile, spec)}';`).join('\n');
	const body = `/** Generated by scripts/generate-browser-test-entries.mjs — do not edit. */
import '../env.ts';
import * as chai from 'chai';

(globalThis as typeof globalThis & { expect: typeof chai.expect }).expect = chai.expect;

${imports}
`;
	fs.mkdirSync(entriesDir, { recursive: true });
	fs.writeFileSync(entryFile, body);
	console.log(`wrote test/browser/entries/${name}.ts (${specPaths.length} specs)`);
}

const unitSpecs = walkSpecs(path.join(repoRoot, 'src/spec'), '.spec.ts');
const exampleSpecs = [
	...walkSpecs(path.join(repoRoot, 'examples'), 'tutorial.spec.ts'),
	path.join(repoRoot, 'examples/shared/interactive.spec.ts'),
].sort();

writeEntry('unit', unitSpecs);
writeEntry('examples', exampleSpecs);
